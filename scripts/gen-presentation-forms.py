# Generates src/core/presentation-forms.ts from the Unicode Character Database that ships with
# Python (unicodedata). It reads no RIFQ data and no Quran text.
#   python3 -I scripts/gen-presentation-forms.py > src/core/presentation-forms.ts
# D-072 (V-26): Arabic presentation forms and ligatures typed or pasted into SEARCH INPUT are read
# as the letters and marks they stand for. The table is the compatibility decomposition of each
# assigned code point in U+FB50..U+FDFF and U+FE70..U+FEFC, except U+FD3E and U+FD3F (V-21).
# A leading U+0020 (isolated mark forms) is dropped. It is never applied to displayed text or to
# the search index, and no Unicode normalization runs at run time: the table is fixed data.
import sys
import unicodedata

rows = []
for cp in list(range(0xFB50, 0xFE00)) + list(range(0xFE70, 0xFEFD)):
    if cp in (0xFD3E, 0xFD3F):
        continue
    ch = chr(cp)
    if unicodedata.category(ch) == 'Cn':
        continue
    d = unicodedata.decomposition(ch)
    if not d:
        continue
    parts = d.split()
    if parts[0].startswith('<'):
        parts = parts[1:]
    out = [int(p, 16) for p in parts]
    while out and out[0] == 0x20:
        out = out[1:]
    if out:
        rows.append((cp, out))

w = sys.stdout.write
w('// GENERATED by scripts/gen-presentation-forms.py from the Unicode Character Database\n')
w('// (Unicode %s). Do not edit by hand. Code points only; no Arabic-script characters.\n' % unicodedata.unidata_version)
w('// D-072 (V-26): search input only. Never applied to displayed text or to the search index.\n')
w('export const PRESENTATION_UNICODE_VERSION = %r;\n' % unicodedata.unidata_version)
w('export const PRESENTATION_FORMS: ReadonlyArray<readonly [number, readonly number[]]> = [\n')
for cp, out in rows:
    w('  [0x%04X, [%s]],\n' % (cp, ', '.join('0x%04X' % c for c in out)))
w('];\n')
